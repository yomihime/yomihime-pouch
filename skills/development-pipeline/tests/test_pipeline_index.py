    def test_concurrent_process_updates_publish_complete_current_index(self):
        runs = [self.init("worker-" + str(i)) for i in range(4)]
        processes = [subprocess.Popen([sys.executable, "-X", "utf8", str(SCRIPT), "note", str(run), "--target", pipeline.read_state(run)["run_id"], "--text", f"worker {i}"], stdout=subprocess.PIPE, stderr=subprocess.PIPE) for i, run in enumerate(runs)]
        errors = []
        # A reader may see either generation, but never a truncated/invalid script.
        while any(p.poll() is None for p in processes):
            try:
                index_data(self.work)
            except (OSError, ValueError, AssertionError) as error:
                errors.append(str(error))
            time.sleep(0.001)
        for process in processes:
            stdout, stderr = process.communicate(timeout=20)
            self.assertEqual(process.returncode, 0, (stdout, stderr))
        self.assertEqual(errors, [])
        entries = self.entries()
        self.assertEqual(len(entries), len(runs))
        for run in runs:
            entry = entries[run.relative_to(self.work).as_posix()]
            self.assertEqual(entry["revision"], pipeline.read_state(run)["revision"])
            self.assertEqual(entry["revision"], 2)


